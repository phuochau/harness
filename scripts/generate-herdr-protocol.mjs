#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const requiredMethods = [
  "workspace.create",
  "workspace.list",
  "workspace.close",
  "worktree.list",
  "worktree.create",
  "worktree.open",
  "worktree.remove",
  "pane.get",
  "pane.process_info",
  "agent.list",
  "agent.get",
  "agent.read",
  "agent.start",
  "agent.prompt",
  "agent.wait",
  "events.subscribe",
];

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

const schemaPath = argument("--schema");
const raw = schemaPath
  ? readFileSync(resolve(schemaPath), "utf8")
  : execFileSync("herdr", ["api", "schema", "--json"], { encoding: "utf8" });
const schema = JSON.parse(raw);
const methods = schema?.schemas?.request?.oneOf?.map(
  (entry) => entry?.properties?.method?.const,
);
if (!Array.isArray(methods) || methods.some((method) => typeof method !== "string")) {
  throw new Error("Herdr schema does not expose schemas.request.oneOf method constants");
}
for (const method of requiredMethods) {
  if (!methods.includes(method)) {
    throw new Error(`installed Herdr schema is missing required method ${method}`);
  }
}
for (const name of [
  "request",
  "success_response",
  "error_response",
  "event",
  "subscription_event",
]) {
  if (schema.schemas?.[name] === undefined) {
    throw new Error(`installed Herdr schema is missing schemas.${name}`);
  }
}

const canonical = canonicalJson(schema);
const hash = `sha256:${createHash("sha256").update(canonical).digest("hex")}`;
const methodLines = [...methods]
  .sort()
  .map((method) => `  ${JSON.stringify(method)},`)
  .join("\n");
const requiredLines = requiredMethods
  .map((method) => `  ${JSON.stringify(method)},`)
  .join("\n");
const source = `// Generated by scripts/generate-herdr-protocol.mjs from herdr api schema --json.\n// Do not edit by hand.\n\nexport const HERDR_SCHEMA_SHA256 = ${JSON.stringify(hash)} as const;\nexport const HERDR_PROTOCOL = ${JSON.stringify(schema.protocol)} as const;\nexport const HERDR_SCHEMA_VERSION = ${JSON.stringify(schema.schema_version)} as const;\n\nexport const HERDR_METHODS = [\n${methodLines}\n] as const;\n\nexport const REQUIRED_HERDR_METHODS = [\n${requiredLines}\n] as const;\n\nexport type HerdrMethod = (typeof HERDR_METHODS)[number];\n\nexport const HERDR_PROTOCOL_SCHEMA: unknown = ${canonical};\n`;

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const output = argument("--output") ??
  resolve(scriptDirectory, "../src/runtime/herdr/protocol.generated.ts");
mkdirSync(dirname(resolve(output)), { recursive: true });
writeFileSync(resolve(output), source, "utf8");
process.stdout.write(`${output}\n${hash}\n`);
